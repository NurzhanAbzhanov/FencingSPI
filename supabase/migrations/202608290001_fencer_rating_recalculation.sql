create table public.fencer_ratings (
    id bigint generated by default as identity primary key,
    season_id uuid not null references public.seasons(id) on delete cascade,
    program_id uuid not null references public.programs(id) on delete cascade,
    weapon public.fencing_weapon not null check (weapon <> 'Team'),
    power_rating numeric not null check (power_rating >= 0),
    source_file text not null,
    imported_by uuid not null references public.profiles(id),
    imported_at timestamptz not null default now()
);

create index fencer_ratings_season_program_weapon_idx
on public.fencer_ratings (season_id, program_id, weapon);

alter table public.fencer_ratings enable row level security;

create policy "Admins read fencer ratings"
on public.fencer_ratings for select
using (public.current_app_role() = 'admin');

create policy "Admins manage fencer ratings"
on public.fencer_ratings for all
using (public.current_app_role() = 'admin')
with check (public.current_app_role() = 'admin');

grant select, insert, update, delete on public.fencer_ratings to authenticated;
grant usage, select on sequence public.fencer_ratings_id_seq to authenticated;

create or replace function public.replace_fencer_ratings_and_recalculate(
    p_season_slug text,
    p_gender public.fencing_gender,
    p_rows jsonb,
    p_source_file text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    target_season_id uuid;
    actor_id uuid := auth.uid();
    invalid_team text;
begin
    if public.current_app_role() <> 'admin' then
        raise exception 'Admin access required';
    end if;

    select id into target_season_id
    from public.seasons
    where slug = btrim(p_season_slug);

    if target_season_id is null then
        raise exception 'Unknown season: %', p_season_slug;
    end if;

    if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
        raise exception 'At least one fencer rating row is required';
    end if;

    if nullif(btrim(p_source_file), '') is null then
        raise exception 'Source filename is required';
    end if;

    if exists (
        select 1
        from jsonb_to_recordset(p_rows) as row(team_name text, weapon text, power_rating numeric)
        where nullif(btrim(row.team_name), '') is null
           or row.weapon not in ('Epee', 'Foil', 'Sabre')
           or row.power_rating is null
           or row.power_rating < 0
    ) then
        raise exception 'Uploaded fencer rating rows are invalid';
    end if;

    select row.team_name into invalid_team
    from jsonb_to_recordset(p_rows) as row(team_name text, weapon text, power_rating numeric)
    where not exists (
        select 1
        from public.schools school
        join public.programs program on program.school_id = school.id
        join public.program_seasons program_season
          on program_season.program_id = program.id
         and program_season.season_id = target_season_id
        where (
                lower(btrim(school.name)) = lower(btrim(row.team_name))
                or (
                    lower(btrim(school.name)) = 'penn state'
                    and lower(btrim(row.team_name)) = 'pennsylvania state university'
                )
              )
          and program.gender = p_gender
    )
    limit 1;

    if invalid_team is not null then
        raise exception 'Could not find % program for team: %', p_gender, invalid_team;
    end if;

    if exists (
        select 1
        from (
            select distinct program.id as program_id
            from jsonb_to_recordset(p_rows) as row(team_name text, weapon text, power_rating numeric)
            join public.schools school on
                lower(btrim(school.name)) = lower(btrim(row.team_name))
                or (
                    lower(btrim(school.name)) = 'penn state'
                    and lower(btrim(row.team_name)) = 'pennsylvania state university'
                )
            join public.programs program
              on program.school_id = school.id
             and program.gender = p_gender
            join public.program_seasons program_season
              on program_season.program_id = program.id
             and program_season.season_id = target_season_id
        ) uploaded_program
        cross join unnest(enum_range(null::public.fencing_weapon)) as required(weapon)
        where not exists (
            select 1
            from public.spi_results result
            where result.season_id = target_season_id
              and result.program_id = uploaded_program.program_id
              and result.weapon = required.weapon
        )
    ) then
        raise exception 'SPI result rows must exist before power ratings can be recalculated';
    end if;

    delete from public.fencer_ratings rating
    using public.programs program
    where rating.season_id = target_season_id
      and rating.program_id = program.id
      and program.gender = p_gender;

    insert into public.fencer_ratings (
        season_id,
        program_id,
        weapon,
        power_rating,
        source_file,
        imported_by
    )
    select
        target_season_id,
        program.id,
        row.weapon::public.fencing_weapon,
        row.power_rating,
        btrim(p_source_file),
        actor_id
    from jsonb_to_recordset(p_rows) as row(team_name text, weapon text, power_rating numeric)
    join public.schools school on
        lower(btrim(school.name)) = lower(btrim(row.team_name))
        or (
            lower(btrim(school.name)) = 'penn state'
            and lower(btrim(row.team_name)) = 'pennsylvania state university'
        )
    join public.programs program
      on program.school_id = school.id
     and program.gender = p_gender
    join public.program_seasons program_season
      on program_season.program_id = program.id
     and program_season.season_id = target_season_id;

    update public.spi_results result
    set power_rating = 0,
        calculated_at = now()
    from public.programs program
    where result.season_id = target_season_id
      and result.program_id = program.id
      and program.gender = p_gender;

    with uploaded_programs as (
        select distinct rating.program_id
        from public.fencer_ratings rating
        join public.programs selected_program
          on selected_program.id = rating.program_id
         and selected_program.gender = p_gender
        where rating.season_id = target_season_id
    ),
    weapons(weapon) as (
        values
            ('Epee'::public.fencing_weapon),
            ('Foil'::public.fencing_weapon),
            ('Sabre'::public.fencing_weapon)
    ),
    ranked as (
        select
            rating.program_id,
            rating.weapon,
            rating.power_rating,
            row_number() over (
                partition by rating.program_id, rating.weapon
                order by rating.power_rating desc, rating.id
            ) as rating_rank
        from public.fencer_ratings rating
        join public.programs program
          on program.id = rating.program_id
         and program.gender = p_gender
        where rating.season_id = target_season_id
    ),
    squad_raw as (
        select
            program.program_id,
            weapon.weapon,
            coalesce(sum(ranked.power_rating) filter (where ranked.rating_rank <= 3), 0) / 3.0 as raw_rating,
            count(ranked.power_rating) as fencer_count
        from uploaded_programs program
        cross join weapons weapon
        left join ranked
          on ranked.program_id = program.program_id
         and ranked.weapon = weapon.weapon
        group by program.program_id, weapon.weapon
    ),
    squad_adjusted as (
        select
            program_id,
            weapon,
            raw_rating,
            case
                when fencer_count = 0 then 0
                when raw_rating < 10 then 10
                when p_gender = 'Men' then floor(raw_rating / 10) * 10
                else ceil(raw_rating / 10) * 10
            end as adjusted_rating
        from squad_raw
    )
    update public.spi_results result
    set power_rating = squad_adjusted.adjusted_rating,
        calculated_at = now()
    from squad_adjusted
    where result.season_id = target_season_id
      and result.program_id = squad_adjusted.program_id
      and result.weapon = squad_adjusted.weapon;

    with uploaded_programs as (
        select distinct rating.program_id
        from public.fencer_ratings rating
        join public.programs selected_program
          on selected_program.id = rating.program_id
         and selected_program.gender = p_gender
        where rating.season_id = target_season_id
    ),
    weapons(weapon) as (
        values
            ('Epee'::public.fencing_weapon),
            ('Foil'::public.fencing_weapon),
            ('Sabre'::public.fencing_weapon)
    ),
    ranked as (
        select
            rating.program_id,
            rating.weapon,
            rating.power_rating,
            row_number() over (
                partition by rating.program_id, rating.weapon
                order by rating.power_rating desc, rating.id
            ) as rating_rank
        from public.fencer_ratings rating
        join public.programs selected_program
          on selected_program.id = rating.program_id
         and selected_program.gender = p_gender
        where rating.season_id = target_season_id
    ),
    squad_raw as (
        select
            program.program_id,
            weapon.weapon,
            coalesce(sum(ranked.power_rating) filter (where ranked.rating_rank <= 3), 0) / 3.0 as raw_rating
        from uploaded_programs program
        cross join weapons weapon
        left join ranked
          on ranked.program_id = program.program_id
         and ranked.weapon = weapon.weapon
        group by program.program_id, weapon.weapon
    ),
    team_raw as (
        select program_id, avg(raw_rating) as raw_rating
        from squad_raw
        group by program_id
    ),
    team_adjusted as (
        select
            program_id,
            case
                when raw_rating < 10 then 10
                when p_gender = 'Men' then floor(raw_rating / 10) * 10
                else ceil(raw_rating / 10) * 10
            end as adjusted_rating
        from team_raw
    )
    update public.spi_results result
    set power_rating = team_adjusted.adjusted_rating,
        calculated_at = now()
    from team_adjusted
    where result.season_id = target_season_id
      and result.program_id = team_adjusted.program_id
      and result.weapon = 'Team';
end;
$$;

revoke all on function public.replace_fencer_ratings_and_recalculate(text, public.fencing_gender, jsonb, text) from public;
grant execute on function public.replace_fencer_ratings_and_recalculate(text, public.fencing_gender, jsonb, text) to authenticated;
