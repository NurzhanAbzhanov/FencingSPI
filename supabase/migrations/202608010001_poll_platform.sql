using (exists (
    select 1 from public.ballots b
    where b.id = ballot_id
      and (b.voter_id = auth.uid() or public.current_app_role() = 'admin' or public.poll_is_closed(b.definition_id))
));
create policy "Coaches edit own rankings" on public.ballot_rankings for all
using (exists (select 1 from public.ballots b where b.id = ballot_id and ((b.voter_id = auth.uid() and public.poll_is_open(b.definition_id)) or public.current_app_role() = 'admin')))
with check (exists (select 1 from public.ballots b where b.id = ballot_id and ((b.voter_id = auth.uid() and public.poll_is_open(b.definition_id)) or public.current_app_role() = 'admin')));

