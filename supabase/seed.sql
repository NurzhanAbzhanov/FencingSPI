insert into public.ballot_definitions (period_id, gender, weapon, scope, rank_limit)
select pp.id, genders.gender, weapons.weapon, scopes.scope,
case when scopes.scope='Overall' then 15 else (select count(*) from public.program_seasons ps join public.programs p on p.id=ps.program_id where ps.season_id=pp.season_id and ps.division=3 and p.gender=genders.gender) end
from public.poll_periods pp
cross join unnest(enum_range(null::public.fencing_gender)) genders(gender)
cross join unnest(enum_range(null::public.fencing_weapon)) weapons(weapon)
cross join unnest(enum_range(null::public.poll_scope)) scopes(scope)
join public.seasons s on s.id=pp.season_id and s.slug='2025-26'
on conflict (period_id,gender,weapon,scope) do update set rank_limit=excluded.rank_limit;

